# Array Basics

arr = [10, 20, 30, 40, 50]

# Print the array
print("Array:", arr)

# Access elements
print("First element:", arr[0])
print("Last element:", arr[-1])

# Traverse the array
print("Array elements:")
for element in arr:
    print(element)

# Find length
print("Length:", len(arr))

# Find sum
print("Sum:", sum(arr))

# Find maximum and minimum
print("Maximum:", max(arr))
print("Minimum:", min(arr))
